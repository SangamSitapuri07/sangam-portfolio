import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { NodeIO } from '@gltf-transform/core'
import { ALL_EXTENSIONS, EXTMeshoptCompression } from '@gltf-transform/extensions'
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer'

const originalURL = new URL('../public/models/cyberpunk_laptop.glb', import.meta.url)
const optimizedURL = new URL('../public/models/cyberpunk_laptop.optimized.glb', import.meta.url)
const hashBlob = (bytes) => createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex')
const originalBytes = await readFile(originalURL)
assert.equal(hashBlob(originalBytes), '42d690d45aa1beacd845759aca38442e21bce93f', 'The supplied source asset changed. Review the new model before regenerating.')

await Promise.all([MeshoptEncoder.ready, MeshoptDecoder.ready])
// Version 0 vertex coding is compatible with Drei's bundled decoder. No
// quantization, simplification, welding, reparenting, or texture conversion is
// applied. The QUANTIZE enum disables meshopt filters; it does not itself run
// glTF Transform's quantize() transform, which is intentionally not imported.
const compatibleEncoder = {
  ...MeshoptEncoder,
  encodeGltfBuffer: (bytes, count, stride, mode) => MeshoptEncoder.encodeGltfBuffer(bytes, count, stride, mode, 0),
}
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({
  'meshopt.encoder': compatibleEncoder,
  'meshopt.decoder': MeshoptDecoder,
})
const source = await io.read(originalURL.pathname)
source.createExtension(EXTMeshoptCompression).setRequired(true).setEncoderOptions({ method: EXTMeshoptCompression.EncoderMethod.QUANTIZE })
await io.write(optimizedURL.pathname, source)
const optimizedBytes = await readFile(optimizedURL)
assert(optimizedBytes.length < originalBytes.length, 'Optimization must actually reduce transfer size.')
const decoded = await io.read(optimizedURL.pathname)
assert.deepEqual(decoded.getRoot().listNodes().map((node) => node.getName()), source.getRoot().listNodes().map((node) => node.getName()))
const metadata = {
  url: '/models/cyberpunk_laptop.optimized.glb',
  bytes: optimizedBytes.length,
  sha: hashBlob(optimizedBytes),
  sourceBytes: originalBytes.length,
  sourceSha: hashBlob(originalBytes),
  compression: 'EXT_meshopt_compression',
  vertexPrecision: 'unchanged',
  textures: 'unchanged',
}
await writeFile(new URL('../src/config/model.generated.js', import.meta.url), `// Generated by npm run assets:optimize. Preserve the original artist file.\nexport const OPTIMIZED_LAPTOP = ${JSON.stringify(metadata, null, 2)}\n`)
console.log(`Original ${originalBytes.length.toLocaleString()} bytes → ${optimizedBytes.length.toLocaleString()} bytes (${((1 - optimizedBytes.length / originalBytes.length) * 100).toFixed(1)}% smaller).`)
